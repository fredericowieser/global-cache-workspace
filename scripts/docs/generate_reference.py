#!/usr/bin/env python3
"""Generate deterministic MyST reference pages from GCW source contracts."""

from __future__ import annotations

import argparse
from dataclasses import MISSING, fields
from pathlib import Path
from typing import Any, get_type_hints

from gcw.cli import build_parser
from gcw.config import (
    CacheProcessorConfig,
    DataConfig,
    EvalConfig,
    FlowProcessorConfig,
    ModelConfig,
    ResumeConfig,
    TrainConfig,
    WandbConfig,
)
from gcw.performance.config import (
    AdaptiveBatchingConfig,
    LongshotFullHistoryConfig,
    NoisyDiffusionBackendConfig,
    PerformanceConfig,
    PhysicalBatchBandConfig,
)

ROOT = Path(__file__).resolve().parents[2]
GENERATED = ROOT / "docs" / "_generated"
CONFIG_TYPES = (
    ModelConfig,
    CacheProcessorConfig,
    FlowProcessorConfig,
    DataConfig,
    PhysicalBatchBandConfig,
    AdaptiveBatchingConfig,
    LongshotFullHistoryConfig,
    NoisyDiffusionBackendConfig,
    PerformanceConfig,
    TrainConfig,
    ResumeConfig,
    WandbConfig,
    EvalConfig,
)


def _display_type(value: Any) -> str:
    return (
        str(value)
        .replace("typing.", "")
        .replace("<class '", "")
        .replace("'>", "")
    )


def _display_default(field: Any) -> str:
    if field.default is not MISSING:
        return repr(field.default)
    if field.default_factory is not MISSING:
        return repr(field.default_factory())
    return "required"


def generate_configuration() -> str:
    lines = [
        "# Configuration schema",
        "",
        "<!-- Generated by scripts/docs/generate_reference.py. Do not edit. -->",
        "",
        "Unknown fields fail during config loading. Defaults below come from the typed dataclass schemas.",
        "",
    ]
    for config_type in CONFIG_TYPES:
        lines.extend(
            [
                f"## `{config_type.__name__}`",
                "",
                "| Field | Type | Default |",
                "|---|---|---|",
            ]
        )
        hints = get_type_hints(config_type)
        for field in fields(config_type):
            field_type = _display_type(
                hints.get(field.name, field.type)
            ).replace("|", "\\|")
            default = (
                _display_default(field).replace("|", "\\|").replace("\n", " ")
            )
            lines.append(f"| `{field.name}` | `{field_type}` | `{default}` |")
        lines.append("")
    return "\n".join(lines).rstrip() + "\n"


def _subcommands(
    parser: argparse.ArgumentParser,
) -> list[tuple[tuple[str, ...], argparse.ArgumentParser]]:
    found: list[tuple[tuple[str, ...], argparse.ArgumentParser]] = []

    def visit(path: tuple[str, ...], current: argparse.ArgumentParser) -> None:
        found.append((path, current))
        for action in current._actions:
            if isinstance(action, argparse._SubParsersAction):
                for name, child in sorted(action.choices.items()):
                    visit((*path, name), child)

    visit((parser.prog,), parser)
    return found


def _action_name(action: argparse.Action) -> str:
    if action.option_strings:
        return ", ".join(f"`{option}`" for option in action.option_strings)
    return f"`{action.dest}`"


def _action_contract(action: argparse.Action) -> str:
    values: list[str] = []
    if getattr(action, "required", False):
        values.append("required")
    if action.choices is not None:
        values.append(
            "choices: " + ", ".join(f"`{choice}`" for choice in action.choices)
        )
    if action.default is not None and action.default is not argparse.SUPPRESS:
        values.append(f"default: `{action.default}`")
    if action.type is not None:
        values.append(
            f"type: `{getattr(action.type, '__name__', str(action.type))}`"
        )
    return "; ".join(values) or "flag"


def generate_cli() -> str:
    lines = [
        "# Command-line reference",
        "",
        "<!-- Generated by scripts/docs/generate_reference.py. Do not edit. -->",
        "",
        "The parser in `gcw.cli` owns this reference.",
        "",
    ]
    for path, parser in _subcommands(build_parser()):
        actions = [
            action
            for action in parser._actions
            if action.dest != "help"
            and not isinstance(action, argparse._SubParsersAction)
        ]
        if len(path) == 1:
            continue
        command = " ".join(path)
        lines.extend(
            [
                f"## `{command}`",
                "",
                "```text",
                parser.format_usage().strip(),
                "```",
                "",
            ]
        )
        if actions:
            lines.extend(["| Argument | Contract |", "|---|---|"])
            for action in actions:
                lines.append(
                    f"| {_action_name(action)} | {_action_contract(action)} |"
                )
            lines.append("")
    return "\n".join(lines).rstrip() + "\n"


def generate_api() -> str:
    return """# Supported Python API

<!-- Generated by scripts/docs/generate_reference.py. Do not edit. -->

The top-level package exposes the intentionally small stable API.

```{automodule} gcw
:members:
:undoc-members: false
```

## Abstract model contracts

```{autoclass} gcw.models.backbones.base.Backbone
:members:
```

```{autoclass} gcw.models.cache_processors.base.CacheProcessorBase
:members:
```
"""


def main() -> None:
    GENERATED.mkdir(parents=True, exist_ok=True)
    outputs = {
        GENERATED / "configuration.md": generate_configuration(),
        GENERATED / "cli.md": generate_cli(),
        GENERATED / "api.md": generate_api(),
    }
    for path, content in outputs.items():
        path.write_text(content, encoding="utf-8")


if __name__ == "__main__":
    main()
